// Pulls every piece of code shown in the video straight from the repo, so the
// demo can never drift from what the compiler actually produces. Re-run after
// regenerating golden files:  npm run sync
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (p) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n");

const lines = (text) => text.replace(/\n+$/, "").split("\n");

// Source kernel, without its explanatory header comment.
const source = lines(read("examples/vector_add.wf")).filter((l) => !l.startsWith("//"));

// saxpy_const IR at -O0 and -O1. An -O0 line is "kept" if an equivalent line
// (ignoring the printer's %N numbering) survives into -O1; everything else is
// folded, propagated, or deleted by the passes and is what the video heats up.
const normalize = (l) => l.replace(/%\d+/g, "%_").trim();
const o0 = lines(read("tests/golden/saxpy_const.ir")).filter((l) => l.trim() !== "");
const o1 = lines(read("tests/golden/saxpy_const.opt.ir")).filter((l) => l.trim() !== "");
const o1Pool = o1.map(normalize);
const irO0 = o0.map((text) => {
  const i = o1Pool.indexOf(normalize(text));
  if (i >= 0) o1Pool[i] = null; // each -O1 line matches at most once
  return { text, kept: i >= 0 };
});

const countPtx = (text) =>
  lines(text).filter((l) => /^\s+[a-z@].*;$/.test(l) && !l.trim().startsWith(".")).length;

// vector_add PTX from the .entry onwards (the module header is shown separately).
const ptxAll = lines(read("tests/golden/vector_add.ptx"));
const entry = ptxAll.findIndex((l) => l.startsWith(".visible .entry"));
const header = ptxAll.filter((l) => l.startsWith(".version") || l.startsWith(".target") || l.startsWith(".address_size"));

const content = {
  source,
  irO0,
  irO1: o1,
  ptxHeader: header,
  ptx: ptxAll.slice(entry).filter((l) => l.trim() !== ""),
  ptxCountO0: countPtx(read("tests/golden/saxpy_const.O0.ptx")),
  ptxCountO1: countPtx(read("tests/golden/saxpy_const.ptx")),
};

writeFileSync(
  join(root, "demo", "src", "content.generated.ts"),
  "// Generated by scripts/sync-content.mjs from the repo's examples and golden files. Do not edit.\n" +
    `export const content = ${JSON.stringify(content, null, 2)} as const;\n`,
);
console.log(
  `synced: ${source.length} source lines, IR ${o0.length} -> ${o1.length} lines ` +
    `(${irO0.filter((l) => !l.kept).length} rewritten or removed), PTX ${content.ptxCountO0} -> ${content.ptxCountO1}`,
);
