TEST(PTX, ModuleHeaderAndEntry) {
  std::string ptx = ptxFor("kernel k(float* o) { o[0] = 1.0; }");
  EXPECT_EQ(ptx, "//\n"
                 "// Generated by WarpForge " WARPFORGE_VERSION "\n"
                 "//\n"
                 "\n"
                 ".version 7.1\n"
                 ".target sm_86\n"
                 ".address_size 64\n"
                 "\n"
                 "\t// .globl\tk\n"
                 ".visible .entry k(\n"
                 "\t.param .u64 k_param_0\n"
                 ")\n"
                 "{\n"
                 "\t.reg .f32 \t%f<2>;\n"
                 "\t.reg .b64 \t%rd<3>;\n"
                 "\n"
                 "\tld.param.u64 \t%rd1, [k_param_0];\n"
                 "\tcvta.to.global.u64 \t%rd2, %rd1;\n"
                 "\tmov.f32 \t%f1, 0f3F800000;\n"
                 "\tst.global.f32 \t[%rd2], %f1;\n"
                 "\tret;\n"
                 "\n"
                 "}\n");
}

TEST(PTX, VectorAddShape) {
  std::string ptx = ptxFor("kernel vector_add(float* a, float* b, float* c, int n) {\n"
                           "  int i = global_id(); if (i < n) { c[i] = a[i] + b[i]; } }");
  for (const char* line : {".visible .entry vector_add(", ".param .u32 vector_add_param_3",
                           "ld.param.u32 \t%r1, [vector_add_param_3];", "mov.u32 \t%r2, %ctaid.x;",
                           "mov.u32 \t%r3, %ntid.x;", "mov.u32 \t%r4, %tid.x;",
                           "mad.lo.s32 \t%r5, %r2, %r3, %r4;", "setp.lt.s32 \t%p1, %r5, %r1;",
                           "@!%p1 bra \t$L__BB0_2;", "mul.wide.s32 \t%rd", "ld.global.f32",
                           "add.rn.f32", "st.global.f32", "$L__BB0_2:\n\tret;"})
    EXPECT_TRUE(has(ptx, line)) << "missing: " << line << "\n" << ptx;
}

TEST(PTX, FloatArithmeticIsRoundToNearest) {
  // Explicit .rn stops ptxas from contracting mul+add into an FMA, which
  // would differ from the folder and the interpreter.
  std::string ptx = ptxFor("kernel k(float* x, float* y) { int i = global_id(); y[i] = 3.0 * x[i] + y[i]; }");
  EXPECT_TRUE(has(ptx, "mul.rn.f32")) << ptx;
  EXPECT_TRUE(has(ptx, "add.rn.f32")) << ptx;
  EXPECT_FALSE(has(ptx, "fma")) << ptx;
}

TEST(PTX, FloatImmediatesAreExactHex) {
  std::string ptx = ptxFor("kernel k(float* o) { int i = global_id(); o[i] = o[i] * 0.1; }");
  EXPECT_TRUE(has(ptx, "0f3DCCCCCD")) << ptx; // 0.1f
}

TEST(PTX, PhiBecomesCopiesOnEdges) {
  std::string ptx = ptxFor("kernel k(float* o, int n) {\n"
                           "  int i = global_id(); float x = 1.0;\n"
                           "  if (i < n) { x = o[i]; }\n"
                           "  o[i] = x * 2.0; }");
  EXPECT_TRUE(has(ptx, "mov.f32")) << ptx; // the phi's copies
  EXPECT_FALSE(has(ptx, "phi")) << ptx;
}

TEST(PTX, ConstantIndexFoldsIntoAddress) {
  std::string ptx = ptxFor("kernel k(float* o) { o[3] = 1.0; }");
  EXPECT_TRUE(has(ptx, "add.s64 \t%rd3, %rd2, 12;")) << ptx;
}

TEST(PTX, NegativeIntegerOps) {
  std::string ptx = ptxFor("kernel k(float* o, int n) { int i = global_id(); int j = -i * n - 1; o[j] = 0.0; }",
                           false);
  for (const char* line : {"neg.s32", "mul.lo.s32", "sub.s32"})
    EXPECT_TRUE(has(ptx, line)) << line << "\n" << ptx;
}

TEST(PTX, FloatNegationIsSignBitXor) {
  // PTX leaves neg.f32 of a NaN unspecified (the RTX 3060 returns 0x7FFFFFFF
  // at run time, while ptxas's folder flips the sign), so float negation is
  // lowered to an exact sign-bit flip instead.
  std::string ptx = ptxFor("kernel k(float* o) { int i = global_id(); o[i] = -o[i]; }");
  EXPECT_TRUE(has(ptx, "xor.b32 \t%f2, %f1, 0x80000000;")) << ptx;
  EXPECT_FALSE(has(ptx, "neg.f32")) << ptx;
}

TEST(PTX, Deterministic) {
  const char* src = "kernel k(float* o, int n) { int i = global_id(); float x = 1.0;"
                    " if (i < n) { x = 2.0; } else { x = o[i]; } o[i] = x; }";
  EXPECT_EQ(ptxFor(src), ptxFor(src));
}

TEST(PTX, MultipleKernels) {
  std::string ptx = ptxFor("kernel a(float* o) { o[0] = 1.0; }\nkernel b(float* o) { o[1] = 2.0; }");
  EXPECT_TRUE(has(ptx, ".visible .entry a(")) << ptx;
  EXPECT_TRUE(has(ptx, ".visible .entry b(")) << ptx;
}

