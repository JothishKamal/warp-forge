#include <map>

using namespace wf;
using codegen::Copy;
using wf::test::compileToIR;

namespace {

// Executes a copy sequence on a register file, one move at a time.
std::map<std::string, int> simulate(const std::vector<Copy>& seq, std::map<std::string, int> regs) {
  for (const Copy& c : seq) regs[c.dst] = regs.at(c.src);
  return regs;
}

std::vector<Copy> sequentialize(std::vector<Copy> copies) {
  int n = 0;
  return codegen::sequentializeParallelCopy(std::move(copies),
                                            [&](const std::string&) { return "t" + std::to_string(n++); });
}

std::string ptxFor(const std::string& source, bool optimize = true) {
  auto m = compileToIR(source);
  if (optimize) {
    passes::PipelineOptions opts;
    opts.passes = passes::defaultPipeline();
    opts.fixpoint = true;
    std::string error;
    EXPECT_TRUE(passes::runPipeline(*m, opts, error)) << error;
  }
  return codegen::emitPTX(*m);
}

bool has(const std::string& text, const std::string& needle) {
  return text.find(needle) != std::string::npos;
}

} // namespace

// ------------------------------------------------------------------ out-of-SSA

TEST(OutOfSSA, SwapCycleUsesTemp) {
  std::vector<Copy> seq = sequentialize({{"a", "b"}, {"b", "a"}});
  EXPECT_EQ(seq.size(), 3u);
  auto regs = simulate(seq, {{"a", 1}, {"b", 2}, {"t0", 0}});
  EXPECT_EQ(regs["a"], 2);
  EXPECT_EQ(regs["b"], 1);
}

TEST(OutOfSSA, ThreeCycle) {
  std::vector<Copy> seq = sequentialize({{"a", "b"}, {"b", "c"}, {"c", "a"}});
  auto regs = simulate(seq, {{"a", 1}, {"b", 2}, {"c", 3}, {"t0", 0}});
  EXPECT_EQ(regs["a"], 2);
  EXPECT_EQ(regs["b"], 3);
  EXPECT_EQ(regs["c"], 1);
}

TEST(OutOfSSA, ChainOrderedWithoutTemp) {
  // b <- a must wait until c has read the old b.
  std::vector<Copy> seq = sequentialize({{"b", "a"}, {"c", "b"}});
  EXPECT_EQ(seq, (std::vector<Copy>{{"c", "b"}, {"b", "a"}}));
}

TEST(OutOfSSA, FanOutAndSelfCopy) {
  std::vector<Copy> seq = sequentialize({{"b", "a"}, {"c", "a"}, {"d", "d"}});
  EXPECT_EQ(seq.size(), 2u); // d <- d dropped
  auto regs = simulate(seq, {{"a", 7}, {"b", 0}, {"c", 0}, {"d", 4}});
  EXPECT_EQ(regs["b"], 7);
  EXPECT_EQ(regs["c"], 7);
}

TEST(OutOfSSA, SplitsCriticalEdge) {
  // entry -> if.end is critical: entry has two successors, if.end two preds.
  auto m = compileToIR("kernel k(float* o, int n) {\n"
                       "  int i = global_id(); float x = 1.0;\n"
                       "  if (i < n) { x = 2.0; }\n"
                       "  o[i] = x; }");
  EXPECT_EQ(codegen::splitCriticalEdges(*m->functions[0]), 1);
  EXPECT_TRUE(ir::verifyModule(*m).empty());
  std::string ir = ir::printModule(*m);
  EXPECT_TRUE(has(ir, "condbr %0, if.then, entry.crit\n")) << ir;
  EXPECT_TRUE(has(ir, "[0x3F800000, entry.crit]")) << ir;
  EXPECT_EQ(codegen::splitCriticalEdges(*m->functions[0]), 0); // idempotent
}

